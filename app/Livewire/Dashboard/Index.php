<?php

namespace App\Livewire\Dashboard;

use App\Models\Admin;
use App\Models\Dashboard;
use App\Models\Panel;
use App\Models\PanelOption;
use Illuminate\Support\Facades\Auth;
use Livewire\Component;

class Index extends Component
{
    public $dashboards_list;

    public $panels_user;

    public $selected_dashboard = null;

    public $subscription_months = 1;

    public $user;

    /*
    |--------------------------------------------------------------------------
    | Gateway
    |--------------------------------------------------------------------------
    */

    public $gateway_key = '';


    /*
    |--------------------------------------------------------------------------
    | Mount
    |--------------------------------------------------------------------------
    */

    public function mount()
    {
        $this->user = Auth::user();

        $this->dashboards_list = Dashboard::all();

        $this->panels_user = Auth::user()
            ->panels()
            ->get();
    }


    /*
    |--------------------------------------------------------------------------
    | Select Dashboard For Subscription
    |--------------------------------------------------------------------------
    */

    public function openSubscriptionModal($dashboardId)
    {
        $dashboard = collect($this->dashboards_list)
            ->firstWhere('id', $dashboardId);

        if (!$dashboard) {
            return;
        }

        $this->selected_dashboard = $dashboard;

        $this->subscription_months = 1;

        $this->resetValidation();
    }


    /*
    |--------------------------------------------------------------------------
    | Open Gateway Settings Modal
    |--------------------------------------------------------------------------
    */

    public function openGatewayModal($dashboardId)
    {
        /*
        |--------------------------------------------------------------------------
        | Find Dashboard
        |--------------------------------------------------------------------------
        */

        $dashboard = collect($this->dashboards_list)
            ->firstWhere('id', $dashboardId);

        if (!$dashboard) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | Select Dashboard
        |--------------------------------------------------------------------------
        */

        $this->selected_dashboard = $dashboard;


        /*
        |--------------------------------------------------------------------------
        | Reset Validation
        |--------------------------------------------------------------------------
        */

        $this->resetValidation();


        /*
        |--------------------------------------------------------------------------
        | Reset Gateway Key
        |--------------------------------------------------------------------------
        |
        | مقدار قبلی را به خاطر امنیت داخل input نشان نمی‌دهیم.
        |
        */

        $this->gateway_key = '';


        /*
        |--------------------------------------------------------------------------
        | Open Flux Modal
        |--------------------------------------------------------------------------
        */

        $this->modal('gateway-settings')->show();
    }


    /*
    |--------------------------------------------------------------------------
    | Save Gateway Settings
    |--------------------------------------------------------------------------
    */

    public function saveGatewaySettings()
    {
        /*
        |--------------------------------------------------------------------------
        | Check Dashboard
        |--------------------------------------------------------------------------
        */

        if (!$this->selected_dashboard) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        $this->validate(
            [
                'gateway_key' => [
                    'required',
                    'string',
                    'min:3',
                    'max:1000',
                ],
            ],
            [
                'gateway_key.required' =>
                    'تنظیمات درگاه را وارد کنید.',

                'gateway_key.min' =>
                    'تنظیمات درگاه معتبر نیست.',

                'gateway_key.max' =>
                    'مقدار تنظیمات درگاه بیش از حد مجاز است.',
            ]
        );


        /*
        |--------------------------------------------------------------------------
        | Find Panel
        |--------------------------------------------------------------------------
        */

        $panel = Panel::where('user_id', Auth::id())
            ->where(
                'dashboard_id',
                $this->selected_dashboard['id']
            )
            ->first();


        /*
        |--------------------------------------------------------------------------
        | Create Panel If Not Exists
        |--------------------------------------------------------------------------
        */

        if (!$panel) {

            $panel = Panel::create([
                'user_id' => Auth::id(),

                'website' => '',

                /*
                |--------------------------------------------------------------------------
                | چون فقط تنظیم درگاه است،
                | اشتراک را اینجا ایجاد نمی‌کنیم.
                |--------------------------------------------------------------------------
                */

                'expired_date' => null,

                'dashboard_id' =>
                    $this->selected_dashboard['id'],

                'key_pass' =>
                    $this->gateway_key,
            ]);


            /*
            |--------------------------------------------------------------------------
            | Create Admin
            |--------------------------------------------------------------------------
            */

            Admin::create([
                'role_id' => 1,

                'panel_id' => $panel->id,

                'user_id' => Auth::id(),

                'password' => '1234',
            ]);


            /*
            |--------------------------------------------------------------------------
            | Create Panel Options
            |--------------------------------------------------------------------------
            */

            for ($optionId = 1; $optionId <= 4; $optionId++) {

                PanelOption::firstOrCreate(
                    [
                        'panel_id' => $panel->id,

                        'option_id' => $optionId,
                    ]
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Website
            |--------------------------------------------------------------------------
            */

            $panel->website =
                'web' . $panel->id;

            $panel->save();

        } else {

            /*
            |--------------------------------------------------------------------------
            | Existing Panel
            |--------------------------------------------------------------------------
            */

            $panel->key_pass =
                $this->gateway_key;

            $panel->save();
        }


        /*
        |--------------------------------------------------------------------------
        | Refresh Panels
        |--------------------------------------------------------------------------
        */

        $this->panels_user = Auth::user()
            ->panels()
            ->get();


        /*
        |--------------------------------------------------------------------------
        | Clear Sensitive Data
        |--------------------------------------------------------------------------
        */

        $this->gateway_key = '';


        /*
        |--------------------------------------------------------------------------
        | Close Modal
        |--------------------------------------------------------------------------
        */

        $this->modal('gateway-settings')->close();
    }


    /*
    |--------------------------------------------------------------------------
    | Pay Subscription
    |--------------------------------------------------------------------------
    */

    public function paySubscription()
    {
        /*
        |--------------------------------------------------------------------------
        | Check Dashboard
        |--------------------------------------------------------------------------
        */

        if (!$this->selected_dashboard) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | Validate Months
        |--------------------------------------------------------------------------
        */

        $months = (int) $this->subscription_months;

        if ($months < 1 || $months > 12) {

            $this->addError(
                'subscription_months',
                'مدت اشتراک باید بین ۱ تا ۱۲ ماه باشد.'
            );

            return;
        }


        /*
        |--------------------------------------------------------------------------
        | Price
        |--------------------------------------------------------------------------
        */

        $price =
            (float) $this->selected_dashboard['per_of_month'];

        $discount =
            (float) $this->selected_dashboard['percentage'];


        /*
        |--------------------------------------------------------------------------
        | Monthly Price After Discount
        |--------------------------------------------------------------------------
        */

        $monthlyPrice =
            $price - (($price * $discount) / 100);


        /*
        |--------------------------------------------------------------------------
        | Total Price
        |--------------------------------------------------------------------------
        */

        $totalPrice =
            $monthlyPrice * $months;


        /*
        |--------------------------------------------------------------------------
        | Find Panel
        |--------------------------------------------------------------------------
        */

        $panel = Panel::where('user_id', Auth::id())
            ->where(
                'dashboard_id',
                $this->selected_dashboard['id']
            )
            ->first();


        /*
        |--------------------------------------------------------------------------
        | Create Panel
        |--------------------------------------------------------------------------
        */

        if (!$panel) {

            /*
            |--------------------------------------------------------------------------
            | Panel
            |--------------------------------------------------------------------------
            */

            $panel = Panel::create([
                'user_id' => Auth::id(),

                'website' => '',

                'expired_date' =>
                    now()->addMonths($months),

                'dashboard_id' =>
                    $this->selected_dashboard['id'],

                /*
                |--------------------------------------------------------------------------
                | اگر gateway قبلاً تنظیم شده باشد
                |--------------------------------------------------------------------------
                */

                'key_pass' =>
                    $this->gateway_key ?: null,
            ]);


            /*
            |--------------------------------------------------------------------------
            | Admin
            |--------------------------------------------------------------------------
            */

            Admin::create([
                'role_id' => 1,

                'panel_id' => $panel->id,

                'user_id' => Auth::id(),

                'password' => '1234',
            ]);


            /*
            |--------------------------------------------------------------------------
            | Panel Options
            |--------------------------------------------------------------------------
            */

            for ($optionId = 1; $optionId <= 4; $optionId++) {

                PanelOption::firstOrCreate(
                    [
                        'panel_id' => $panel->id,

                        'option_id' => $optionId,
                    ]
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Website
            |--------------------------------------------------------------------------
            */

            $panel->website =
                'web' . $panel->id;

            $panel->save();

        } else {

            /*
            |--------------------------------------------------------------------------
            | Existing Panel
            |--------------------------------------------------------------------------
            |
            | اگر اشتراک قبلی هنوز فعال است،
            | مدت جدید را به تاریخ انقضای قبلی اضافه می‌کنیم.
            |
            */

            $baseDate =
                $panel->expired_date &&
                now()->lt($panel->expired_date)
                    ? $panel->expired_date
                    : now();


            $panel->expired_date =
                $baseDate->copy()->addMonths($months);


            /*
            |--------------------------------------------------------------------------
            | Gateway
            |--------------------------------------------------------------------------
            */

            if (!empty($this->gateway_key)) {

                $panel->key_pass =
                    $this->gateway_key;
            }


            /*
            |--------------------------------------------------------------------------
            | Website
            |--------------------------------------------------------------------------
            */

            if (empty($panel->website)) {

                $panel->website =
                    'web' . $panel->id;
            }


            $panel->save();
        }


        /*
        |--------------------------------------------------------------------------
        | Refresh Panels
        |--------------------------------------------------------------------------
        */

        $this->panels_user = Auth::user()
            ->panels()
            ->get();


        /*
        |--------------------------------------------------------------------------
        | Clear Sensitive Gateway Value
        |--------------------------------------------------------------------------
        */

        $this->gateway_key = '';


        /*
        |--------------------------------------------------------------------------
        | Close Subscription Modal
        |--------------------------------------------------------------------------
        */

        $this->modal('subscription')->close();


        /*
        |--------------------------------------------------------------------------
        | TODO: Payment Gateway
        |--------------------------------------------------------------------------
        |
        | در مرحله بعد اینجا:
        |
        | 1. Reserve Payment
        | 2. Create Authority
        | 3. Redirect To Gateway
        | 4. Callback
        | 5. Verify Payment
        | 6. Create Payment
        | 7. Extend Panel
        |
        |--------------------------------------------------------------------------
        */

        // TODO:
        // Create payment
        // Redirect to gateway
    }


    /*
    |--------------------------------------------------------------------------
    | Is Paid
    |--------------------------------------------------------------------------
    */

    public function is_paid($dashboardId)
    {
        return $this->panels_user
            ->where('dashboard_id', $dashboardId)
            ->isNotEmpty();
    }


    /*
    |--------------------------------------------------------------------------
    | Render
    |--------------------------------------------------------------------------
    */

    public function render()
    {
        return view(
            'livewire.dashboard.index'
        )->layout('layouts.blank');
    }
}
